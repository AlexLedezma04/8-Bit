//! Writes a Zig file that embeds every `.zon` file of a folder, so adding a
//! file there needs no list to be kept in sync.
//! Usage: embed_dir <name prefix> <folder> <output.zig>
const std = @import("std");

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(arena);
    const prefix, const folder, const output = .{ args[1], args[2], args[3] };

    var names: std.ArrayList([]const u8) = .empty;
    var dir = try std.Io.Dir.cwd().openDir(io, folder, .{ .iterate = true });
    defer dir.close(io);
    var entries = dir.iterate();
    while (try entries.next(io)) |entry| {
        if (entry.kind == .file and std.mem.endsWith(u8, entry.name, ".zon")) try names.append(arena, try arena.dupe(u8, entry.name));
    }
    std.mem.sort([]const u8, names.items, {}, lessThan);

    var text: std.Io.Writer.Allocating = .init(arena);
    const out = &text.writer;
    try out.writeAll("//! Generated by tools/embed_dir.zig.\npub const files = .{\n");
    for (names.items) |name| {
        const bytes = try dir.readFileAlloc(io, name, arena, .unlimited);
        try out.print("    .{{ \"{s}/{s}\", \"{f}\" }},\n", .{ prefix, name[0 .. name.len - ".zon".len], std.zig.fmtString(bytes) });
    }
    try out.writeAll("};\n");
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = output, .data = text.written() });
}

fn lessThan(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.lessThan(u8, a, b);
}
