//! Packs the built-in data files into one deflated blob, so they cost less
//! in the exe, and writes a Zig file with the blob, its unpacked size and
//! where each file is in it. A folder adds each of its `.zon` files as
//! `name/file`, so adding one needs no list to be kept in sync, without
//! spaces and comments outside strings. A file is kept as it is: the user
//! gets a copy of the settings to edit.
//! Usage: pack <output.zig> (<name> <file or folder>)...
const std = @import("std");

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(arena);

    var data: std.ArrayList(u8) = .empty;
    var index: std.Io.Writer.Allocating = .init(arena);
    const out = &index.writer;
    var i: usize = 2;
    while (i + 1 < args.len) : (i += 2) {
        const name, const path = .{ args[i], args[i + 1] };
        if ((try std.Io.Dir.cwd().statFile(io, path, .{})).kind != .directory) {
            try add(arena, out, &data, name, try std.Io.Dir.cwd().readFileAlloc(io, path, arena, .unlimited));
            continue;
        }
        var dir = try std.Io.Dir.cwd().openDir(io, path, .{ .iterate = true });
        defer dir.close(io);
        var names: std.ArrayList([]const u8) = .empty;
        var entries = dir.iterate();
        while (try entries.next(io)) |entry| {
            if (entry.kind == .file and std.mem.endsWith(u8, entry.name, ".zon")) try names.append(arena, try arena.dupe(u8, entry.name));
        }
        std.mem.sort([]const u8, names.items, {}, lessThan);
        for (names.items) |file| {
            const stem = file[0 .. file.len - ".zon".len];
            try add(arena, out, &data, try std.fmt.allocPrint(arena, "{s}/{s}", .{ name, stem }), try minify(arena, try dir.readFileAlloc(io, file, arena, .unlimited)));
        }
    }

    var deflated: std.Io.Writer.Allocating = try .initCapacity(arena, data.items.len);
    const compress = try arena.create(std.compress.flate.Compress);
    compress.* = try .init(&deflated.writer, try arena.alloc(u8, std.compress.flate.max_window_len), .raw, .best);
    try compress.writer.writeAll(data.items);
    try compress.finish();

    const text = try std.fmt.allocPrint(arena,
        \\//! Generated by tools/pack.zig.
        \\pub const size = {d};
        \\/// Name, then start and length; each file is followed by a 0 byte.
        \\pub const files = .{{
        \\{s}}};
        \\/// Raw deflate.
        \\pub const deflated = "{f}";
        \\
    , .{ data.items.len, index.written(), std.zig.fmtString(deflated.written()) });
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = args[1], .data = text });
}

/// Appends a file, and its entry to the index.
fn add(arena: std.mem.Allocator, index: *std.Io.Writer, data: *std.ArrayList(u8), name: []const u8, bytes: []const u8) !void {
    try index.print("    .{{ \"{s}\", .{{ {d}, {d} }} }},\n", .{ name, data.items.len, bytes.len });
    try data.appendSlice(arena, bytes);
    try data.append(arena, 0);
}

/// ZON without spaces and `//` comments. Strings, characters and `\\`
/// lines stay as they are.
fn minify(arena: std.mem.Allocator, text: []const u8) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    var i: usize = 0;
    while (i < text.len) {
        const c = text[i];
        if (c == '"' or c == '\'') {
            var end = i + 1;
            while (end < text.len and text[end] != c) end += if (text[end] == '\\') 2 else 1;
            try out.appendSlice(arena, text[i..@min(end + 1, text.len)]);
            i = end + 1;
        } else if (std.mem.startsWith(u8, text[i..], "\\\\")) {
            const end = std.mem.findScalarPos(u8, text, i, '\n') orelse text.len;
            try out.appendSlice(arena, text[i..@min(end + 1, text.len)]);
            i = end + 1;
        } else if (std.mem.startsWith(u8, text[i..], "//")) {
            i = std.mem.findScalarPos(u8, text, i, '\n') orelse text.len;
        } else {
            if (!std.ascii.isWhitespace(c)) try out.append(arena, c);
            i += 1;
        }
    }
    return out.items;
}

fn lessThan(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.lessThan(u8, a, b);
}
